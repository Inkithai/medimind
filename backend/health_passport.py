# PDF rendering
# ---------------------------------------------------------------------------


def _wrap(text: str, fontname: str, fontsize: float, max_width: float, fitz: Any) -> List[str]:
    """Word-wrap `text` to `max_width` using PyMuPDF's text measurement."""
    words = text.split()
    lines: List[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        width = fitz.get_text_length(candidate, fontname=fontname, fontsize=fontsize)
        if not current or width <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def _draw_section(
    page: Any,
    fitz: Any,
    y: float,
    title: str,
    items: List[str],
    accent: Any,
    accent_light: Any,
    empty_text: str = "None recorded",
) -> float:
    """Draw one section, wrapping to the content width, and return the new Y.

    Keeps the whole page to one sheet: if the section would overflow the
    footer reserve, items are dropped and a "+N more" line is appended.
    """
    line_height = 12.6
    gap_after = 14.0
    bottom = PAGE_HEIGHT - FOOTER_RESERVE

    # Section heading.
    if y + 13 > bottom:
        return y
    page.insert_text(
        (MARGIN, y + 9.0),
        title,
        fontname=TITLE_FONT,
        fontsize=10.5,
        color=accent,
    )
    y += 15.0

    body_lines: List[str] = []
    shown = 0
    truncated = False
    for item in items:
        wrapped = _wrap(f"\u2022  {item}", BODY_FONT, 9.3, CONTENT_WIDTH, fitz)
        if y + (len(body_lines) + len(wrapped)) * line_height > bottom:
            truncated = True
            break
        body_lines.extend(wrapped)
        shown += 1

    if not body_lines:
        empty = _wrap(f"\u2022  {empty_text}", BODY_FONT, 9.3, CONTENT_WIDTH, fitz)
        if y + len(empty) * line_height <= bottom:
            body_lines = empty

    if truncated and shown < len(items):
        more = _wrap(
            f"\u2022  +{len(items) - shown} more not shown",
            BODY_FONT,
            9.3,
            CONTENT_WIDTH,
            fitz,
        )
        if y + (len(body_lines) + len(more)) * line_height <= bottom:
            body_lines.extend(more)

    for line in body_lines:
        page.insert_text(
            (MARGIN, y + 9.0),
            line,
            fontname=BODY_FONT,
            fontsize=9.3,
            color=INK,
        )
        y += line_height
    return y + gap_after


def render_passport_pdf(data: Dict[str, Any]) -> bytes:
    """Render the passport as a single-page PDF and return its bytes."""
    try:
        import fitz  # PyMuPDF
    except Exception as exc:  # pragma: no cover - environment-specific
        raise RuntimeError(
            "PyMuPDF is required to generate the health passport PDF but could not be imported."
        ) from exc

    doc = fitz.open()
    page = doc.new_page(width=PAGE_WIDTH, height=PAGE_HEIGHT)

    # Header band.
    header_h = 74.0
    page.draw_rect(
        fitz.Rect(0, 0, PAGE_WIDTH, header_h),
        color=None,
        fill=ACCENT_LIGHT,
        width=0,
    )
    page.insert_text(
        (MARGIN, 40.0),
        "Health Passport",
        fontname=TITLE_FONT,
        fontsize=20.0,
        color=INK,
    )
    page.insert_text(
        (MARGIN, 55.0),
        "A one-page summary of my health for a new doctor",
        fontname=BODY_FONT,
        fontsize=9.5,
        color=MUTED,
    )
    patient = str(data.get("patient_name") or "Not recorded")
    prepared = f"Prepared {data.get('generated_at', '')}"
    page.insert_text(
        (MARGIN, 69.0),
        f"Patient: {patient}",
        fontname=TITLE_FONT,
        fontsize=10.0,
        color=INK,
    )
    prepared_width = fitz.get_text_length(prepared, fontname=BODY_FONT, fontsize=8.5)
    page.insert_text(
        (PAGE_WIDTH - MARGIN - prepared_width, 69.0),
        prepared,
        fontname=BODY_FONT,
        fontsize=8.5,
        color=MUTED,
    )

    y = header_h + 10.0
    sections = [
        (
            "Active medications",
            data.get("active_medications") or [],
            ACCENT,
            ACCENT_LIGHT,
            "No active medications on record",
        ),
        (
            "Allergies",
            data.get("allergies") or [],
            RED,
            RED_LIGHT,
            "No allergies recorded",
        ),
        (
            "Key conditions",
            data.get("conditions") or [],
            VIOLET,
            VIOLET_LIGHT,
            "No conditions recorded",
        ),
        (
            "Recent abnormal labs",
            data.get("recent_abnormal_labs") or [],
            ACCENT,
            ACCENT_LIGHT,
            "No abnormal labs recorded",
        ),
    ]
    for title, items, accent, accent_light, empty_text in sections:
        y = _draw_section(page, fitz, y, title, items, accent, accent_light, empty_text)

    # Footer.
    footer = (
        "Generated by MediMind from uploaded records. This is a summary, not a diagnosis — "
        "confirm every item with your clinician. In an emergency, contact your local "
        "emergency service."
    )
    wrapped_footer = _wrap(footer, BODY_FONT, 7.5, CONTENT_WIDTH, fitz)
    fy = PAGE_HEIGHT - FOOTER_RESERVE + 10.0
    for line in wrapped_footer:
        page.insert_text((MARGIN, fy), line, fontname=BODY_FONT, fontsize=7.5, color=MUTED)
        fy += 9.0

    try:
        return doc.tobytes(garbage=3, deflate=True)
    finally:
        doc.close()


def build_health_passport_pdf(
    timeline: Dict[str, Any],
    cross_check: Optional[Dict[str, Any]] = None,
    lab_trends: Optional[Dict[str, Any]] = None,
    patient_name: Optional[str] = None,
    workspace_name: Optional[str] = None,
) -> bytes:
    """End-to-end: record -> passport data -> single-page PDF bytes."""
    data = build_passport_data(
        timeline,
        cross_check=cross_check,
        lab_trends=lab_trends,
        patient_name=patient_name,
        workspace_name=workspace_name,
    )
    return render_passport_pdf(data)
